/**
 * Shared TypeScript types used across the Monome monorepo.
 * Keep this package dependency-free (no imports from @monome/ai or @monome/db)
 * so it can be safely imported anywhere without creating cycles.
 */

/** Which AI backend is currently active. Chosen by the user in Settings. */
export type AiProviderKind = "ollama" | "openai" | "anthropic" | "gemini";

/** Roles for a single message inside a conversation, mirrors ChatGPT export roles. */
export type MessageRole = "user" | "assistant" | "system";

/** A single chat message as stored in the immutable raw layer. */
export interface RawMessage {
  id: string;
  conversationId: string;
  role: MessageRole;
  content: string;
  createdAt: string;
}

/** A single imported conversation (raw layer, never overwritten after import). */
export interface RawConversation {
  id: string;
  title: string;
  source: "chatgpt-export" | "pasted";
  createdAt: string;
  messages: RawMessage[];
}

/** A chunk of a conversation prepared for embedding (~500 tokens). */
export interface Chunk {
  id: string;
  conversationId: string;
  text: string;
  /** Index of this chunk within its conversation, for ordering. */
  order: number;
}

/** A chunk plus its embedding vector, ready to be written to LanceDB. */
export interface EmbeddedChunk extends Chunk {
  embedding: number[];
}

/** A ranked semantic search result returned from LanceDB. */
export interface SearchResult {
  chunkId: string;
  conversationId: string;
  text: string;
  /** Lower distance = more similar (raw LanceDB metric, not normalized). */
  distance: number;
}

/**
 * Structured note generated by the chat model from a conversation. Always
 * cites its source (conversationId is set by the pipeline, never by the
 * model's own output).
 */
export interface GeneratedNote {
  conversationId: string;
  /** A better short title, or null if the original conversation title is fine. */
  titleOverride: string | null;
  summary: string;
  topics: string[];
  keyIdeas: string[];
  decisions: string[];
  openQuestions: string[];
}

/**
 * The exact shape we ask the chat model to return as JSON for note
 * generation. Validated before ever touching GeneratedNote/the database -
 * this is untrusted model output until it passes parseNotePayload.
 */
export interface RawNotePayload {
  title: string | null;
  summary: string;
  topics: string[];
  keyIdeas: string[];
  decisions: string[];
  openQuestions: string[];
}

/** A message extracted from an import source, before it has a DB id. */
export interface ParsedMessage {
  role: MessageRole;
  content: string;
  /** ISO timestamp if the source provided one, otherwise null. */
  createdAt: string | null;
}

/** A conversation extracted from an import source, before it's written to SQLite. */
export interface ParsedConversation {
  /** Best-effort human title. Falls back to "Untitled conversation" if missing. */
  title: string;
  source: "chatgpt-export" | "pasted";
  messages: ParsedMessage[];
}

/** One conversation in the export that failed to parse and was skipped. */
export interface ImportWarning {
  /** Best-effort identifier for the skipped item (title, index, or id if available). */
  identifier: string;
  reason: string;
}

/** Result of an import run, returned to the UI for the "Imported X, skipped Y" summary. */
export interface ImportSummary {
  importedCount: number;
  skippedCount: number;
  warnings: ImportWarning[];
  /** Ids of the conversations that were successfully created, for convenience. */
  importedConversationIds: string[];
}
